import { useState } from "react";
import { useAsync } from "./hooks/useAsync";
import { DashboardPage } from "./pages/DashboardPage";
import { EventsPage } from "./pages/EventsPage";
import { IncidentPage } from "./pages/IncidentPage";
import { api } from "./services/api";

type Tab = "incidents" | "events";

export default function App() {
  const [tab, setTab] = useState<Tab>("incidents");
  const [incidentId, setIncidentId] = useState<number | null>(null);
  const health = useAsync(() => api.health(), []);

  return (
    <div className="app">
      <header>
        <h1>TRACE <small>Threat Reconstruction and Analysis Console</small></h1>
        <nav>
          <button className={tab === "incidents" ? "active" : ""} onClick={() => { setTab("incidents"); setIncidentId(null); }}>
            Incidents
          </button>
          <button className={tab === "events" ? "active" : ""} onClick={() => setTab("events")}>
            Events
          </button>
        </nav>
        <span className={health.error ? "error" : "muted"}>
          {health.error ? "API offline" : health.data ? `API ${health.data.status}` : "Checking API…"}
        </span>
      </header>
      <main>
        {tab === "events" && <EventsPage />}
        {tab === "incidents" &&
          (incidentId === null ? (
            <DashboardPage onOpenIncident={setIncidentId} />
          ) : (
            <IncidentPage incidentId={incidentId} onBack={() => setIncidentId(null)} />
          ))}
      </main>
      <footer className="muted">
        Incidents are potential incidents generated by deterministic rules over synthetic data, not confirmed attacks.
      </footer>
    </div>
  );
}
